#!/usr/bin/env python3
"""Prepare a clean source ZIP and user-facing notes for a reviewed release draft."""
import argparse
import hashlib
import importlib.util
from pathlib import Path
import subprocess
import zipfile

from release_notes import VERSION, generate

ROOT = Path(__file__).resolve().parents[1]


def prepare(version, destination):
    if not VERSION.fullmatch(version) or '-preview.' not in version:
        raise ValueError('Source-only automation currently supports vX.Y.Z-preview.N')
    if subprocess.run(['git', 'rev-parse', '--verify', 'refs/tags/' + version], cwd=ROOT,
                      stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).returncode == 0:
        raise ValueError('The release tag already exists')
    destination = destination.resolve()
    if destination.exists():
        raise ValueError('Choose a fresh output directory')
    notes = generate(ROOT, version)
    spec = importlib.util.spec_from_file_location('export_public', ROOT / 'scripts/export-public.py')
    exporter = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(exporter)
    source = destination / 'source'
    exporter.export_source(ROOT, source)
    archive = destination / f'orbit-dashboard-{version}.zip'
    files = subprocess.check_output(['git', 'ls-tree', '-r', '--name-only', 'HEAD'], cwd=ROOT, text=True).splitlines()
    # Only committed export entries enter the ZIP, never artifacts generated by tests.
    with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED) as output:
        for name in files:
            output.write(source / name, f'orbit-dashboard-{version}/{name}')
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    (destination / 'SHA256SUMS.txt').write_text(f'{digest}  {archive.name}\n')
    (destination / 'release-notes.md').write_text(notes)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version', required=True)
    parser.add_argument('--output', required=True, type=Path)
    options = parser.parse_args()
    try:
        prepare(options.version, options.output)
    except (ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, str(error) + '\n')
